// `pnpm signal:client`: writes lib/signal/client.ts, the typed fetch client, from the operation
// registry. Every spec 001 operation gets a method (planned ones type their input as `never`
// until their task builds them), so building an operation never changes this file; adding or
// renaming one does. `tests/signal/client.test.ts` fails when the routes are stale.
import { execFileSync } from "node:child_process";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { allOperations } from "@/lib/signal/operations/registry";

const root = path.resolve(import.meta.dirname, "..");
const operationsDir = path.join(root, "lib/signal/operations");
export const clientPath = path.join(root, "lib/signal/client.ts");

const notOperationFiles = new Set(["execute.ts", "registry.ts", "types.ts"]);

const camelCase = (name: string) =>
  name.replaceAll(/_(?<letter>\w)/gu, (_, letter: string) => letter.toUpperCase());

/** Each registry entry with the module and export that define it. */
const locateOperations = async () => {
  const entries = await readdir(operationsDir);
  const files = entries
    .filter((file) => file.endsWith(".ts") && !notOperationFiles.has(file))
    .toSorted();
  const located = new Map<unknown, { exportName: string; module: string }>();
  for (const file of files) {
    // oxlint-disable-next-line eslint/no-await-in-loop -- a few small modules, read in order
    const exports = (await import(pathToFileURL(path.join(operationsDir, file)).href)) as Record<
      string,
      unknown
    >;
    for (const [exportName, value] of Object.entries(exports))
      if (allOperations.includes(value as never))
        located.set(value, { exportName, module: `./operations/${file.replace(/\.ts$/u, "")}` });
  }
  return allOperations
    .map((operation) => {
      const found = located.get(operation);
      if (!found) throw new Error(`No module exports operation ${operation.name}.`);
      return { ...found, method: camelCase(operation.name), operation };
    })
    .toSorted((a, b) => (a.operation.name < b.operation.name ? -1 : 1));
};

export const renderSignalClient = async () => {
  const entries = await locateOperations();
  const imports = entries
    .map(({ exportName, module }) => `import type { ${exportName} } from "${module}";`)
    .join("\n");
  const routes = entries
    .map(
      ({ operation }) =>
        `  ${operation.name}: { access: "${operation.access}", method: "${operation.http.method}", name: "${operation.name}", path: "${operation.http.path}" },`,
    )
    .join("\n");
  const types = entries
    .map(
      ({ exportName, operation }) =>
        `  ${operation.name}: { input: InputOf<typeof ${exportName}>; output: OutputOf<typeof ${exportName}> };`,
    )
    .join("\n");
  const byMethod = entries.toSorted((a, b) => (a.method < b.method ? -1 : 1));
  const methods = byMethod
    .map(
      ({ method, operation }) =>
        `  ${method}: (input: SignalOperations["${operation.name}"]["input"], call?: SignalCallOptions) => Promise<SignalResult<SignalOperations["${operation.name}"]["output"]>>;`,
    )
    .join("\n");
  const factory = byMethod
    .map(
      ({ method, operation }) =>
        `    ${method}: (input, call) => callSignalOperation(signalRoutes.${operation.name}, input, options, call),`,
    )
    .join("\n");

  return `// Generated by scripts/generate-signal-client.ts from lib/signal/operations/registry.ts.
// Do not edit by hand: run \`pnpm signal:client\`.
//
// The typed fetch client for every Signal operation (spec 001 → Typed API contract). The UI
// calls Signal only through this client. Type-only imports keep it safe for the browser.
import type { z } from "zod";

import { callSignalOperation } from "./client-runtime";
import type { SignalCallOptions, SignalClientOptions, SignalResult } from "./client-runtime";
${imports}

export type { SignalCallOptions, SignalClientError, SignalClientOptions, SignalResult } from "./client-runtime";

/** Input as callers send it (before defaults); \`never\` until the operation is built. */
type InputOf<T> = T extends { input: infer I extends z.ZodType } ? z.input<I> : never;
/** Output as the server returns it (after parsing); \`never\` until the operation is built. */
type OutputOf<T> = T extends { output: infer O extends z.ZodType } ? z.output<O> : never;

export const signalRoutes = {
${routes}
} as const;

export type SignalOperationName = keyof typeof signalRoutes;

export interface SignalOperations {
${types}
}

export interface SignalClient {
${methods}
}

export const createSignalClient = (options: SignalClientOptions = {}): SignalClient => ({
${factory}
});
`;
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await writeFile(clientPath, await renderSignalClient());
  execFileSync("pnpm", ["exec", "oxfmt", "--write", clientPath], { cwd: root, stdio: "inherit" });
  console.log(`[signal:client] Wrote ${path.relative(root, clientPath)}`);
}
